// The owner's secrets form (docs/leap/core/SECRETS.md). Shown inside the install approval
// (mode "install": the values travel with the approval) and on the app page (mode "change":
// the values file an app.configure the owner then approves). It never fetches and never shows
// a stored value: the hub only says which keys are set. The caller seals the submission with
// sealValues() before anything leaves the browser, and the typed values are dropped from state
// as soon as they are handed over.
import { useEffect, useId, useRef, useState, type FormEvent } from 'react';
import { Button } from '../components/Button';
import { Icon } from '../components/Icon';
import { StatusPill } from '../components/StatusPill';
import { KIND_LABEL, compactValues, refOf, submissionProblems } from './logic';
import type { AppSecrets, SecretKeyState, SecretValues, SecretsSubmission } from './types';
import './secrets.css';

export interface SecretsFormProps {
  app: { id: string; name: string };
  secrets: AppSecrets;
  mode: 'install' | 'change';
  submitLabel?: string;
  busy?: boolean;
  /** The gateway's error message (it never contains a value). */
  error?: string;
  onSubmit: (submission: SecretsSubmission) => void;
  onCancel?: () => void;
}

export function SecretsForm({ app, secrets, mode, submitLabel, busy = false, error, onSubmit, onCancel }: SecretsFormProps) {
  const [values, setValues] = useState<SecretValues>({});
  const [shown, setShown] = useState<Set<string>>(new Set());
  const [rotate, setRotate] = useState<Set<string>>(new Set());
  const [clear, setClear] = useState<Set<string>>(new Set());
  const [problems, setProblems] = useState<Record<string, string>>({});
  const formRef = useRef<HTMLFormElement>(null);
  const uid = useId();
  // Typed values are dropped when the form goes away (closing the card, navigating).
  useEffect(() => () => setValues({}), []);

  const set = (secret: string, key: string, v: string) => setValues((prev) => ({ ...prev, [secret]: { ...prev[secret], [key]: v } }));
  const toggle = (which: Set<string>, setter: (s: Set<string>) => void, ref: string) => {
    const next = new Set(which);
    if (next.has(ref)) next.delete(ref);
    else next.add(ref);
    setter(next);
  };

  const submit = (e: FormEvent) => {
    e.preventDefault();
    const sub: SecretsSubmission = { values: compactValues(values), generate: [...rotate], clear: [...clear] };
    const found = submissionProblems(secrets, sub, mode);
    setProblems(found);
    if (Object.keys(found).length) {
      const first = Object.keys(found).find((k) => k !== '_form');
      if (first) formRef.current?.querySelector<HTMLElement>(`[data-ref="${CSS.escape(first)}"]`)?.focus();
      return;
    }
    onSubmit(sub);
    setValues({});
    setShown(new Set());
  };

  const fieldId = (ref: string) => `${uid}-${ref.replace(/[^a-zA-Z0-9_-]/g, '_')}`;

  const row = (secretName: string, k: SecretKeyState) => {
    const ref = refOf(secretName, k.key);
    const id = fieldId(ref);
    const problem = problems[ref];
    const status = k.set ? (
      <StatusPill tone="ok" label="Set" detail={k.version ? `version ${k.version}` : undefined} />
    ) : (
      <StatusPill tone={k.required ? 'warn' : 'neutral'} label="Not set" dot={false} />
    );
    if (k.source === 'generated') {
      return (
        <li key={ref} className="om-sec-row">
          <div className="om-sec-head">
            <span className="om-sec-key">{k.key}</span>
            <StatusPill tone="info" label="Generated by the box" dot={false} />
            {status}
          </div>
          {k.description && <p className="om-hint">{k.description}</p>}
          {mode === 'change' ? (
            <label className="om-sec-check">
              <input type="checkbox" checked={rotate.has(ref)} onChange={() => toggle(rotate, setRotate, ref)} />
              <span>Rotate: replace it with a new random value</span>
            </label>
          ) : (
            <p className="om-hint">{k.set ? 'Kept as it is.' : 'Created at install. Nobody needs to type it.'}</p>
          )}
        </li>
      );
    }
    const visible = shown.has(ref);
    const clearing = clear.has(ref);
    const hintId = `${id}-hint`;
    const errId = `${id}-err`;
    return (
      <li key={ref} className="om-sec-row">
        <div className="om-sec-head">
          <label className="om-sec-key" htmlFor={id}>
            {k.key}
          </label>
          <StatusPill tone="neutral" label={KIND_LABEL[k.kind]} dot={false} />
          {k.required ? <StatusPill tone="warn" label="Required" dot={false} /> : null}
          {status}
        </div>
        <p className="om-hint" id={hintId}>
          {k.description || 'No description.'}
          {k.set ? ' Leave empty to keep the stored value; it is never shown.' : ''}
        </p>
        <div className="om-sec-input">
          <input
            id={id}
            data-ref={ref}
            type={k.kind === 'url' || visible ? (k.kind === 'url' ? 'url' : 'text') : 'password'}
            inputMode={k.kind === 'url' ? 'url' : undefined}
            autoComplete={k.kind === 'password' ? 'new-password' : 'off'}
            autoCapitalize="off"
            spellCheck={false}
            disabled={busy || clearing}
            value={values[secretName]?.[k.key] ?? ''}
            onChange={(e) => set(secretName, k.key, e.target.value)}
            aria-invalid={problem ? true : undefined}
            aria-describedby={problem ? `${errId} ${hintId}` : hintId}
            placeholder={k.set ? 'Set · type to replace' : k.kind === 'url' ? 'https://' : ''}
          />
          {k.kind !== 'url' && (
            <Button
              size="sm"
              variant="ghost"
              aria-pressed={visible}
              aria-controls={id}
              onClick={() => toggle(shown, setShown, ref)}
              disabled={busy || clearing}
            >
              {visible ? 'Hide' : 'Show'}
            </Button>
          )}
        </div>
        {problem && (
          <p className="om-sec-error" id={errId}>
            <Icon name="alert" size={16} /> {problem}
          </p>
        )}
        {mode === 'change' && k.set && !k.required && (
          <label className="om-sec-check">
            <input type="checkbox" checked={clearing} onChange={() => toggle(clear, setClear, ref)} disabled={busy} />
            <span>Clear: remove the stored value</span>
          </label>
        )}
      </li>
    );
  };

  return (
    <form ref={formRef} className="om-sec" onSubmit={submit} noValidate aria-label={`Secrets for ${app.name}`}>
      <p className="om-sec-lede">
        <Icon name="lock" size={18} />
        <span>
          {mode === 'install' ? `${app.name} needs these to run. ` : `Change or rotate what ${app.name} uses. `}
          What you type is encrypted in this browser to your box (key <code>{secrets.key_id}</code>), stored encrypted, and never shown again: not
          to you, not to agents.{mode === 'change' ? ' Saving files a change you approve; the app restarts with the new values.' : ''}
        </span>
      </p>
      {secrets.secrets.map((s) => (
        <fieldset key={s.name} className="om-sec-group">
          <legend>
            <span className="om-sec-name">{s.name}</span>
            {s.description && <span className="om-hint"> · {s.description}</span>}
          </legend>
          <ul className="om-sec-list">{s.keys.map((k) => row(s.name, k))}</ul>
        </fieldset>
      ))}
      {(problems._form || error) && (
        <p className="om-note om-tone-bad" role="alert">
          {problems._form ?? error}
        </p>
      )}
      <div className="om-sec-actions">
        {onCancel && (
          <Button variant="secondary" onClick={onCancel} disabled={busy}>
            Cancel
          </Button>
        )}
        <Button type="submit" variant="primary" busy={busy}>
          {submitLabel ?? (mode === 'install' ? 'Approve with these secrets' : 'Request this change')}
        </Button>
      </div>
    </form>
  );
}
