"""The private app bundle a plan produces, on the box's disk.

    <bundle>/onemind.app.yaml          the app manifest (origin: private)
    <bundle>/manifests/                one file per object + kustomization.yaml (the real app)
    <bundle>/staging/kustomization.yaml  the same objects with every workload at 0 replicas
    <bundle>/scan.json                 the scan record, written by the on-box scan (not hashed)

`import` applies staging/ (volumes and config exist, nothing runs, so no app starts on an
empty volume); `copy` restores data into the volumes and then applies manifests/ (side by
side with the old cluster). The bundle hash covers every file except scan.json, and an
approval is refused if the files changed after the request.
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
import tempfile
from pathlib import Path

import yaml

from ..catalog import AppEntry

SCAN_FILE = "scan.json"
APP_LABEL = "onemind.io/app"


def _dump(doc: dict) -> str:
    return yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, allow_unicode=True)


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9-]+", "-", text.lower()).strip("-")


HEADER = "# SPDX-License-Identifier: Apache-2.0\n# Generated by onemind migrate; edit the source cluster and re-plan instead.\n"


def write_bundle(root: Path, manifest: dict, objects: list[dict], workloads: list[dict]) -> str:
    """Write the bundle atomically (temp dir, then rename) and return its sha256."""
    root.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=f".{root.name}-", dir=root.parent))
    try:
        (tmp / "manifests").mkdir()
        (tmp / "staging").mkdir()
        (tmp / "onemind.app.yaml").write_text(HEADER + _dump(manifest))
        files = []
        for i, obj in enumerate(objects):
            fname = f"{i:02d}-{_slug(obj['kind'])}-{_slug(obj['metadata']['name'])}.yaml"
            (tmp / "manifests" / fname).write_text(HEADER + _dump(obj))
            files.append(fname)
        app_id = manifest["metadata"]["id"]
        kustom = {
            "apiVersion": "kustomize.config.k8s.io/v1beta1",
            "kind": "Kustomization",
            "resources": files,
            "labels": [{"pairs": {APP_LABEL: app_id}, "includeSelectors": False, "includeTemplates": True}],
        }
        (tmp / "manifests" / "kustomization.yaml").write_text(HEADER + _dump(kustom))
        staging = {
            "apiVersion": "kustomize.config.k8s.io/v1beta1",
            "kind": "Kustomization",
            "resources": ["../manifests"],
            "replicas": [{"name": w["name"], "count": 0} for w in workloads],
        }
        (tmp / "staging" / "kustomization.yaml").write_text(HEADER + _dump(staging))
        digest = bundle_sha256(tmp)
        if root.exists():
            shutil.rmtree(root)
        os.replace(tmp, root)
        return digest
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise


def bundle_sha256(root: Path) -> str:
    """sha256 over (relative path, file sha256) of every file but scan.json, in sorted order."""
    h = hashlib.sha256()
    for path in sorted(p for p in root.rglob("*") if p.is_file()):
        rel = path.relative_to(root).as_posix()
        if rel == SCAN_FILE:
            continue
        h.update(rel.encode() + b"\0" + hashlib.sha256(path.read_bytes()).hexdigest().encode() + b"\n")
    return "sha256:" + h.hexdigest()


def entry(root: Path, manifest: dict, *, staging: bool) -> AppEntry:
    """An AppEntry the executor can apply: staging/ (0 replicas) or manifests/ (the real app)."""
    spec = dict(manifest.get("spec") or {})
    spec["manifests"] = "staging/" if staging else "manifests/"
    return AppEntry(id=manifest["metadata"]["id"], dir=root, manifest={**manifest, "spec": spec})
