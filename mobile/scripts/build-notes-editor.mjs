// Bundles the offline WebView editor (ProseMirror + y-prosemirror + Yjs) into one JS string the app embeds.
// The output is git-ignored (src/spikes/notes/editorBundle.generated.ts); `npm start/android/ios` runs this first.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const r = await build({
  entryPoints: ['src/spikes/notes/webEditor.entry.js'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2019',
  write: false,
  legalComments: 'none',
});
const js = r.outputFiles[0].text;
writeFileSync('src/spikes/notes/editorBundle.generated.ts', `// Generated by scripts/build-notes-editor.mjs. Do not edit or commit.\nexport const EDITOR_JS = ${JSON.stringify(js)};\n`);
console.log(`notes editor bundle: ${(js.length / 1024).toFixed(0)} KiB minified`);
