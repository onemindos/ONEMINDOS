"""Raspberry Pi 5 boot configuration and MBR layout (brief 30 BD-07, D-B2.2; 01 §4.2).

Pure functions, unit-tested in test/unit/test_rpi5.py; os/boards/rpi5/assemble_rpi5.py uses them.

A/B method: the Pi firmware's partition-level A/B ("tryboot_a_b" in autoboot.txt) driven by
RAUC's custom bootloader backend (os/boards/rpi5/rootfs/usr/lib/onemind/rpi-tryboot-ab.sh), the
layout the F-PI5 kit desk-checked [C-LAB-rauc-1152-013, -017]. Sources:
  autoboot.txt / tryboot_a_b / [boot_partition=N] filters: raspberrypi/documentation@21d772e7
    documentation/asciidoc/computers/config_txt/autoboot.adoc and conditional.adoc
  kernel_2712.img / kernel8.img names: raspi-firmware 1:1.20260915-1 /etc/kernel/postinst.d/z50-raspi-firmware
  force_eeprom_read, camera_auto_detect, display_auto_detect: brief 30 §6 B2 table, rpi5 row (E10)
MBR on-disk format: the classic DOS partition table (UEFI spec 2.10 §5.2.1 "Legacy MBR") with
extended boot records chaining the logical partitions 5..7, as sfdisk writes them.
"""
import struct

SECTOR = 512
ALIGN = 2048                      # 1 MiB, as sfdisk and the Pi kit use
MBR_TYPES = {"fat32": 0x0C, "extended": 0x05, "linux": 0x83}
KERNELS = {"2712": ("kernel_2712.img", "initramfs_2712"),   # 16 KiB pages, the Pi 5 default
           "v8": ("kernel8.img", "initramfs8")}             # 4 KiB pages (LT-PI5-01 step A1 fallback)
SLOT_PART = {"A": (2, 5), "B": (3, 6)}                      # slot -> (boot partition, root partition)


def partuuid(disk_id, number):
    """Linux's PARTUUID for an MBR partition: <disk signature>-<partition number, 2 hex digits>."""
    return f"{int(disk_id, 16):08x}-{number:02x}"


def cmdline(board, slot):
    _, root = SLOT_PART[slot]
    # Same flags as the GRUB boards (os/assemble/grub.cfg.in CMDLINE); cgroup flags for k3s on the
    # Raspberry Pi kernel, as the F-PI5 kit used.
    return (f"{board['console']} root=PARTUUID={partuuid(board['disk_id'], root)} rootfstype=ext4 "
            f"panic=10 rootwait ro loglevel=4 cgroup_enable=memory cgroup_memory=1 rauc.slot={slot}\n")


def config_txt(board):
    kernel, initramfs = KERNELS[str(board["kernel"])]
    return f"""# OneMind OS, board rpi5: generated by os/boards/rpi5/rpi5_boot.py. Both boot slots carry this
# same file; the [boot_partition=N] filters pick the slot's kernel command line.
[all]
arm_64bit=1
kernel={kernel}
initramfs {initramfs} followkernel
# E10 (brief 30 B2): the EEPROM's own config wins, no camera/display probing, overlays only from
# this boot slot (the default overlay_prefix; no os_prefix).
force_eeprom_read=0
camera_auto_detect=0
display_auto_detect=0
# serial console on the GPIO header (console=serial0 in cmdline_*.txt)
enable_uart=1
# NVMe on the PCIe connector (a no-op without an adapter; HAT+ boards are enabled anyway)
dtparam=pciex1

[boot_partition=2]
cmdline=cmdline_a.txt
[boot_partition=3]
cmdline=cmdline_b.txt
[all]
"""


def autoboot_txt(committed):
    """autoboot.txt with `committed` as the normal slot; the other one is the tryboot slot."""
    c = SLOT_PART[committed][0]
    t = 3 if c == 2 else 2
    return f"[all]\ntryboot_a_b=1\nboot_partition={c}\n[tryboot]\nboot_partition={t}\n"


def boot_files(board):
    """Generated text files of one boot slot (kernels, dtbs and overlays are copied separately)."""
    return {"config.txt": config_txt(board), "cmdline_a.txt": cmdline(board, "A"),
            "cmdline_b.txt": cmdline(board, "B")}


# ------------------------------------------------------------------ MBR
def mib(size):
    s = str(size).strip()
    if s == "rest":
        return None
    for suf, mul in (("GiB", 1024), ("MiB", 1)):
        if s.endswith(suf):
            return int(float(s[: -len(suf)]) * mul)
    raise ValueError(f"size must end in GiB or MiB, or be 'rest': {size!r}")


def plan(layout):
    """Partition geometry in sectors: {number: (label, type, first_lba, n_sectors)} plus EBR LBAs.

    Partitions 1-3 primary, 4 the extended container to the end of the disk, 5.. logical. Each
    logical partition sits 1 MiB after its EBR (sfdisk's default)."""
    parts = layout["partitions"]
    nums = [p["number"] for p in parts]
    assert nums == sorted(nums) and len(set(nums)) == len(nums), "partitions must be in number order"
    assert [p["number"] for p in parts if p["type"] != "extended" and p["number"] <= 4] == [1, 2, 3], "1-3 primary"
    ext = [p for p in parts if p["type"] == "extended"]
    assert len(ext) == 1 and ext[0]["number"] == 4 and ext[0]["size"] == "rest", "4 = extended, size rest"
    total = mib(layout["disk_size"]) * (1 << 20) // SECTOR
    geo, ebrs, lba = {}, [], ALIGN
    for p in parts:
        n = p["number"]
        size = mib(p["size"])
        if n <= 3:
            geo[n] = (p["label"], p["type"], lba, size * 2048)
            lba += size * 2048
        elif n == 4:
            geo[4] = (p["label"], "extended", lba, total - lba)
        else:
            ebr = lba
            first = ebr + ALIGN
            count = (total - first) if size is None else size * 2048
            assert size is not None or p is parts[-1], "only the last partition may be 'rest'"
            assert first + count <= total, f"{p['label']} does not fit the disk"
            geo[n] = (p["label"], p["type"], first, count)
            ebrs.append((n, ebr))
            lba = first + count
    return {"total": total, "parts": geo, "ebrs": ebrs}


def _entry(ptype, first, count, boot=False):
    # CHS fields set to the "beyond 8 GiB" marker FE FF FF; everyone reads the LBA fields.
    return struct.pack("<B3sB3sII", 0x80 if boot else 0, b"\xfe\xff\xff", ptype, b"\xfe\xff\xff", first, count)


def _sector(entries, disk_id=None):
    s = bytearray(SECTOR)
    if disk_id is not None:
        struct.pack_into("<I", s, 0x1B8, int(disk_id, 16))
    for i, e in enumerate(entries):
        s[0x1BE + 16 * i: 0x1BE + 16 * (i + 1)] = e
    s[0x1FE:0x200] = b"\x55\xaa"
    return bytes(s)


def mbr_sectors(layout, disk_id):
    """{lba: 512-byte sector} for the MBR and every EBR."""
    g = plan(layout)
    P = g["parts"]
    ext_first = P[4][2]
    out = {0: _sector([_entry(MBR_TYPES[P[n][1]], P[n][2], P[n][3]) for n in (1, 2, 3, 4)], disk_id)}
    for i, (n, ebr) in enumerate(g["ebrs"]):
        _, t, first, count = P[n]
        ents = [_entry(MBR_TYPES[t], first - ebr, count)]
        if i + 1 < len(g["ebrs"]):
            nn, nebr = g["ebrs"][i + 1]
            nfirst, ncount = P[nn][2], P[nn][3]
            ents.append(_entry(MBR_TYPES["extended"], nebr - ext_first, nfirst + ncount - nebr))
        out[ebr] = _sector(ents)
    return out


def parse_mbr(read_sector):
    """Read back a disk: {"disk_id": hex, "parts": {number: (type, first_lba, n_sectors)}}.
    `read_sector(lba)` returns 512 bytes. Follows the EBR chain like the Linux kernel does."""
    def entries(sec):
        assert sec[0x1FE:0x200] == b"\x55\xaa", "missing 55AA signature"
        res = []
        for i in range(4):
            _, _, t, _, first, count = struct.unpack_from("<B3sB3sII", sec, 0x1BE + 16 * i)
            res.append((t, first, count))
        return res
    m = read_sector(0)
    out = {"disk_id": f"{struct.unpack_from('<I', m, 0x1B8)[0]:08x}", "parts": {}}
    ext = None
    for i, (t, first, count) in enumerate(entries(m), 1):
        if t:
            out["parts"][i] = (t, first, count)
            if t in (0x05, 0x0F):
                ext = first
    n, ebr = 5, ext
    while ebr is not None and n < 64:
        e = entries(read_sector(ebr))
        t, first, count = e[0]
        out["parts"][n] = (t, ebr + first, count)
        n += 1
        ebr = ext + e[1][1] if e[1][0] in (0x05, 0x0F) else None
    return out
