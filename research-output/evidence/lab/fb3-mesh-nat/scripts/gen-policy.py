"""Generate a Headscale (Tailscale-format) ACL policy from OneMind roles.
Roles: hub, worker, leaf (machines, as tags), app (tag on an app's own node),
owner-device (user-owned phones/laptops). Default deny: only listed flows pass."""
import json, sys
OWNER = sys.argv[1] if len(sys.argv) > 1 else "onemind@"
LAB_ALLOWED_LEAF_PEER_PORT = "9001"   # lab-only: the one leaf-to-leaf service the test allows
FLOWS = [  # (src roles, dst role, ports, why)
    (["leaf", "worker"], "hub", "7422", "NATS leaf link to the hub (TLS + per-node creds)"),
    (["worker"], "hub", "6443", "k3s agent to server API"),
    (["worker", "hub"], "worker", "10250,51820", "kubelet and flannel wireguard-native between k3s nodes"),
    (["hub"], "worker", "*", "hub manages workers"),
    (["hub"], "leaf", "*", "hub manages leaves"),
    (["owner-device"], "hub", "443", "phone/laptop to the gateway (login enforced by the gateway)"),
    (["leaf"], "leaf", LAB_ALLOWED_LEAF_PEER_PORT, "lab: one allowed leaf-to-leaf service"),
]
def ref(role):
    return OWNER if role == "owner-device" else f"tag:{role}"
policy = {
    "tagOwners": {f"tag:{r}": [OWNER] for r in ("hub", "worker", "leaf", "app")},
    "acls": [],
}
for srcs, dst, ports, why in FLOWS:
    policy["acls"].append({"action": "accept", "src": [ref(s) for s in srcs],
                           "dst": [f"{ref(dst)}:{ports}"], "//": why})
# Tailscale policy files are HuJSON; "//" keys are not allowed, so move the reasons out.
reasons = [a.pop("//") for a in policy["acls"]]
print("// generated by gen-policy.py from OneMind roles; default deny")
for i, r in enumerate(reasons):
    print(f"// acl[{i}]: {r}")
print(json.dumps(policy, indent=2))
