"""First-boot seed for the OneMind Hermes app (runs as an init container, stdlib only).

When $HERMES_HOME/config.yaml does not exist yet, it writes Hermes's own example config
(/opt/hermes/cli-config.yaml.example, which the image's stage2 hook would otherwise seed)
plus the OneMind block (seed/onemind.yaml: the mcp_servers.onemind entry) and a dashboard
login. Once config.yaml exists it does nothing, so the owner's edits are never overwritten.

Why a dashboard login: the dashboard listens on 0.0.0.0:9119 so the Service can reach it,
and Hermes refuses to start a non-loopback dashboard without an auth provider (upstream
docs, website/docs/user-guide/features/web-dashboard.md). The seed generates a random
password, stores only its scrypt hash in config.yaml (dashboard.basic_auth, the format of
plugins/dashboard_auth/basic.hash_password) and writes the plaintext to
$HERMES_HOME/onemind-dashboard-password (mode 0600) for the owner to read once.
HERMES_DASHBOARD_BASIC_AUTH_USERNAME / _PASSWORD in the owner's Secret
hermes-agent-credentials override it (env wins in Hermes).
"""
import base64
import hashlib
import os
import secrets
import sys

HOME = os.environ.get("HERMES_HOME", "/opt/data")
EXAMPLE = "/opt/hermes/cli-config.yaml.example"
ONEMIND = os.path.join(os.path.dirname(os.path.abspath(__file__)), "onemind.yaml")
CONFIG = os.path.join(HOME, "config.yaml")
PASSWORD_FILE = os.path.join(HOME, "onemind-dashboard-password")


def scrypt_hash(password: str) -> str:
    # Same parameters and encoding as Hermes v0.23.0 plugins/dashboard_auth/basic.hash_password.
    n, r, p = 2**14, 8, 1
    salt = secrets.token_bytes(16)
    dk = hashlib.scrypt(password.encode(), salt=salt, n=n, r=r, p=p, dklen=32, maxmem=0)
    return f"scrypt${n}${r}${p}${base64.b64encode(salt).decode()}${base64.b64encode(dk).decode()}"


def make_run_dir() -> None:
    # s6-overlay's preinit refuses a /run that the (non-root) container UID does not own.
    run_dir = os.environ.get("ONEMIND_RUN_DIR")
    if run_dir:
        os.makedirs(run_dir, mode=0o755, exist_ok=True)
        os.chmod(run_dir, 0o755)


def main() -> int:
    make_run_dir()
    if os.path.lexists(CONFIG):
        print(f"[onemind-seed] {CONFIG} exists; leaving it to the owner")
        return 0
    os.makedirs(HOME, exist_ok=True)
    parts = []
    if os.path.isfile(EXAMPLE):
        with open(EXAMPLE, encoding="utf-8") as f:
            parts.append(f.read().rstrip("\n") + "\n")
    with open(ONEMIND, encoding="utf-8") as f:
        parts.append("\n" + "".join(l for l in f if not l.startswith("# SPDX-")))
    password = secrets.token_urlsafe(18)
    parts.append(
        "\n# Dashboard login generated by the OneMind seed on first boot; the password is in\n"
        "# onemind-dashboard-password next to this file. Signing secret keeps sessions across restarts.\n"
        "dashboard:\n"
        "  basic_auth:\n"
        "    username: owner\n"
        f"    password_hash: \"{scrypt_hash(password)}\"\n"
        f"    secret: \"{secrets.token_hex(32)}\"\n")
    old = os.umask(0o077)
    try:
        with open(PASSWORD_FILE + ".tmp", "w", encoding="utf-8") as f:
            f.write(password + "\n")
        os.replace(PASSWORD_FILE + ".tmp", PASSWORD_FILE)
        with open(CONFIG + ".tmp", "w", encoding="utf-8") as f:
            f.write("".join(parts))
        os.replace(CONFIG + ".tmp", CONFIG)
    finally:
        os.umask(old)
    print(f"[onemind-seed] wrote {CONFIG} with the OneMind MCP entry and a dashboard login (user 'owner')")
    return 0


if __name__ == "__main__":
    sys.exit(main())
