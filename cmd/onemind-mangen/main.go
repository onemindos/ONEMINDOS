// Command onemind-mangen writes the onemind man pages (onemind.1, onemind-apps.1, ...) from the
// Cobra command tree, so the pages can never drift from the CLI. It is a build tool: the image
// build and the CLI package build run it, and it is not shipped. Usage: onemind-mangen <out-dir> [version].
package main

import (
	"fmt"
	"io"
	"os"
	"time"

	"github.com/spf13/cobra/doc"

	"github.com/onemindos/onemindos/cmd/onemind/cli"
)

func main() {
	if len(os.Args) < 2 || len(os.Args) > 3 {
		fmt.Fprintln(os.Stderr, "usage: onemind-mangen <out-dir> [version]")
		os.Exit(2)
	}
	version := "dev"
	if len(os.Args) == 3 {
		version = os.Args[2]
	}
	if err := generate(os.Args[1], version); err != nil {
		fmt.Fprintln(os.Stderr, "onemind-mangen:", err)
		os.Exit(1)
	}
}

func generate(dir, version string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	root, _ := cli.NewRoot(cli.Env{Stdout: io.Discard, Stderr: io.Discard})
	root.DisableAutoGenTag = true // no "Auto generated by spf13/cobra on <date>": the pages build the same every time
	// A fixed date keeps the build reproducible; SOURCE_DATE_EPOCH is the standard way to set it.
	when := time.Unix(0, 0).UTC()
	if s := os.Getenv("SOURCE_DATE_EPOCH"); s != "" {
		var sec int64
		if _, err := fmt.Sscan(s, &sec); err != nil {
			return fmt.Errorf("SOURCE_DATE_EPOCH %q: %w", s, err)
		}
		when = time.Unix(sec, 0).UTC()
	}
	return doc.GenManTree(root, &doc.GenManHeader{Title: "ONEMIND", Section: "1", Source: "OneMind OS " + version,
		Manual: "OneMind OS", Date: &when}, dir)
}
