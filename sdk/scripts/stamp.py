"""Put the "generated" header with the spec's sha256 on a generated Go or Python file (SDK.md §3.4).

    python3 scripts/stamp.py <file> <tool and version>
"""

import hashlib
import re
import sys
from pathlib import Path

SPEC = Path(__file__).resolve().parent.parent / "openapi" / "onemind-v1.json"


def main() -> int:
    path, tool = Path(sys.argv[1]), sys.argv[2]
    c = "//" if path.suffix == ".go" else "#"
    sha = hashlib.sha256(SPEC.read_bytes()).hexdigest()
    body = path.read_text(encoding="utf-8")
    body = re.sub(rf"^{re.escape(c)} (Spec sha256: [0-9a-f]+|SPDX-License-Identifier: Apache-2.0)\n", "", body, flags=re.M)
    head = (f"{c} Code generated by {tool} from sdk/openapi/onemind-v1.json. DO NOT EDIT.\n"
            f"{c} SPDX-License-Identifier: Apache-2.0\n{c} Spec sha256: {sha}\n")
    if path.suffix == ".go":  # keep oapi-codegen's own "Code generated" line (Go tooling reads it)
        body = body.replace("// Code generated by", "// Generator:", 1)
    path.write_text(head + body, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
