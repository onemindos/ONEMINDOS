"""Generate apps/<id>/README.md (contract §9.3) from onemind.app.yaml, the rendered manifests
and scan.json. Hand-written text (what the app is, packaging notes, first-run steps copied from the
upstream docs with their URL) lives between the notes markers and is kept on every regeneration."""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import common, licence

NOTES_BEGIN = "<!-- onemind:notes:begin -->"
NOTES_END = "<!-- onemind:notes:end -->"
HEADER = ("<!-- SPDX-License-Identifier: Apache-2.0 -->\n"
          "<!-- Generated by sdk/tools/app-readme from onemind.app.yaml, manifests/ and scan.json "
          "(contract sdk/contracts/poc-v0.md §9.3). Edit only between the onemind:notes markers, "
          "then run: python3 -I sdk/tools/app-readme <id> -->\n")


def default_notes(docs_url: str) -> str:
    return ("## First run\n\n"
            f"UNVERIFIED: copy the first-run steps from the upstream documentation ({docs_url}) "
            "and cite the page they come from.\n")


def extract_notes(text: str) -> str | None:
    m = re.search(re.escape(NOTES_BEGIN) + r"\n?(.*?)\n?" + re.escape(NOTES_END), text, re.S)
    return m.group(1).strip("\n") + "\n" if m else None


def link(url: str | None) -> str:
    if not url or url == common.UNVERIFIED:
        return common.UNVERIFIED
    return f"<{url}>"


def fmt_res(section: dict) -> str:
    return " / ".join(str(section.get(k, "-")) for k in ("cpu", "memory"))


def render(app_dir: Path, objects: list[dict] | None = None) -> str:
    m = common.load_manifest(app_dir)
    meta, spec = m["metadata"], m["spec"]
    links = meta.get("links") or {}
    up = meta.get("upstream") or {}
    scan_path = app_dir / "scan.json"
    scan = json.loads(scan_path.read_text(encoding="utf-8")) if scan_path.is_file() else None
    if objects is None:
        objects = common.render(app_dir / spec["manifests"])
    old = (app_dir / "README.md").read_text(encoding="utf-8") if (app_dir / "README.md").is_file() else ""
    notes = extract_notes(old) or default_notes(links.get("docs") or common.UNVERIFIED)

    if scan:
        lic_class = f"**{scan['licence']['class']}** (licence gate, scan of {scan['scanned_at'][:10]})"
    else:
        lic_class = f"{licence.classify(meta['license'])} by SPDX id; not yet confirmed by the licence gate"
    released = up.get("released_at") or common.UNVERIFIED
    rows = [
        ("Version", f"{meta['version']} (upstream release `{up.get('release', common.UNVERIFIED)}`, "
                    f"published {released[:10] if released != common.UNVERIFIED else released})"),
        ("Licence", f"`{meta['license']}`, Market class {lic_class}"),
        ("Tier", f"`{meta.get('tier', common.UNVERIFIED)}` (set by CI: sdk/tools/app-gate)"),
        ("Category", meta["category"]),
        ("GitHub", link(links.get("github") or meta.get("source"))),
        ("Website", link(links.get("website"))),
        ("Docs", link(links.get("docs"))),
        ("Support", link(links.get("support"))),
        ("Upstream archived", "yes" if up.get("archived") else "no"),
        ("Architectures", ", ".join(spec.get("archs") or []) or common.UNVERIFIED),
        ("Web UI", f"port {spec['web']['port']}" if spec.get("web") else "none"),
    ]
    upd = spec.get("updates") or {}
    rows.append(("Updates", f"channel `{upd.get('channel', '-')}`, automerge `{upd.get('automerge', '-')}`"))
    agent = spec.get("agent")
    if agent and agent.get("principal"):
        rows.append(("Agent principal", f"yes: the gateway creates `agent:{meta['id']}` and Secret "
                                        f"`{agent.get('secret')}` at install (contract §11.2)"))

    out = [HEADER, f"# {meta['name']}\n", f"{meta['description']}\n", "| | |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in rows]

    req = spec.get("requires") or {}
    out += ["", "## Resources", "",
            f"The Market lists `minMemoryMb: {req.get('minMemoryMb')}`"
            f"{' and needs a GPU' if req.get('gpu') else ', no GPU'}.", ""]
    res_rows, pvcs = common.resources_summary(objects)
    if res_rows:
        out += ["| Workload | Container | Requests (CPU / memory) | Limits (CPU / memory) |",
                "|---|---|---|---|"]
        out += [f"| {r['workload']} | {r['container']} | {fmt_res(r['requests'])} | {fmt_res(r['limits'])} |"
                for r in res_rows]
    if pvcs:
        out += ["", "Storage: " + ", ".join(f"PVC `{p['name']}` {p['size']}" for p in pvcs) + "."]
    out += ["", "Images:", ""] + [f"- `{img}`" for img in common.images(objects)]

    out += ["", NOTES_BEGIN, notes.rstrip("\n"), NOTES_END, "", "## Latest security scan", ""]
    if not scan:
        out.append("No scan yet. `sdk/tools/app-gate` writes `scan.json` (contract §9.4, §11.1).")
    else:
        out += [f"Scanned {scan['scanned_at']} by `sdk/tools/app-gate`: **{scan['result']}**. "
                f"Licence `{scan['licence']['spdx']}` class {scan['licence']['class']}; "
                f"smoke test {scan['smoke']}.", "",
                "| Image | Archs | CRITICAL (with fix) | HIGH | ClamAV | Secrets | cosign |",
                "|---|---|---|---|---|---|---|"]
        for i in scan["images"]:
            t, c = i["trivy"], i["clamav"]
            out.append(f"| `{i['ref']}` | {', '.join(i['archs'])} | {t['critical']} ({t['critical_fixable']}) | "
                       f"{t['high']} | {c['infected']} infected ({c['signatures']}) | {i['secrets']} | {i['cosign']} |")
        out += ["", f"Trivy {scan['images'][0]['trivy']['version'] if scan['images'] else '-'}. "
                    "A CRITICAL with a fix available fails the gate; other findings are recorded."]
    return "\n".join(out) + "\n"
