# Make random owner + agent tokens for the compose dev stack (contract §3, v0 static tokens).
# Writes ./local/owner.token and ./local/agent.token (mode 0600, gitignored) and
# ./local/tokens.yaml, which holds only sha256 hashes. Re-run with --force to rotate.
set -eu
cd "$(dirname "$0")"
if [ -f local/tokens.yaml ] && [ "${1:-}" != --force ]; then
  echo "local/tokens.yaml exists (use --force to make new tokens)"; exit 0
fi
umask 077
mkdir -p local
rand() { od -An -N32 -tx1 /dev/urandom | tr -d ' \n'; }
sha() { if command -v sha256sum >/dev/null; then printf %s "$1" | sha256sum; else printf %s "$1" | shasum -a 256; fi | cut -d' ' -f1; }
owner=$(rand); agent=$(rand)
printf '%s\n' "$owner" > local/owner.token
printf '%s\n' "$agent" > local/agent.token
cat > local/tokens.yaml <<YAML
# compose dev principals (generated by gen-tokens.sh; hashes only)
tokens:
  "sha256:$(sha "$owner")": {id: owner, kind: person, role: owner}
  "sha256:$(sha "$agent")": {id: dev-agent, kind: agent, role: agent}
YAML
chmod 0644 local/tokens.yaml   # read by the gateway container's uid 10001; holds no secret
echo "tokens written to $(pwd)/local (owner.token, agent.token)"
