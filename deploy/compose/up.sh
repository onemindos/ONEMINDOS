# Start the OneMind Mac hub: generate local API tokens once, build, start, wait.
# Tokens live in deploy/compose/.secrets/ (git-ignored) and never leave the Mac.
# The gateway's tokens file holds only sha256 hashes of the tokens.
set -euo pipefail
cd "$(dirname "$0")"

port="${ONEMIND_HUB_PORT:-8080}"
command -v docker >/dev/null || { echo "Docker is required (Docker Desktop on the Mac)" >&2; exit 2; }
docker info >/dev/null 2>&1 || { echo "Docker is not running" >&2; exit 2; }

sha256_hex() { if command -v sha256sum >/dev/null 2>&1; then printf '%s' "$1" | sha256sum | cut -d' ' -f1; else printf '%s' "$1" | shasum -a 256 | cut -d' ' -f1; fi; }

mkdir -p .secrets
chmod 700 .secrets
if [ ! -s .secrets/tokens.yaml ] || ! grep -q '^tokens:' .secrets/tokens.yaml; then
  owner="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  agent="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  umask 077
  cat > .secrets/tokens.yaml <<EOF
# Local demo tokens generated by up.sh (sha256 hashes only). Never commit; this folder is git-ignored.
tokens:
  "sha256:$(sha256_hex "$owner")": {id: owner, kind: person, role: owner}
  "sha256:$(sha256_hex "$agent")": {id: dev-agent, kind: agent, role: agent}
EOF
  # The container user (uid 10001) must read the mounted file; the folder stays 0700.
  chmod 644 .secrets/tokens.yaml
  printf '%s\n' "$owner" > .secrets/owner.token
  printf '%s\n' "$agent" > .secrets/agent.token
  echo "Generated new tokens in deploy/compose/.secrets/"
fi

# --remove-orphans: services dropped from this file (older demo layouts) are stopped,
# so the Nodes screen shows only the machines defined here.
docker compose up -d --build --remove-orphans
# 127.0.0.1, not localhost: on a Mac "localhost" may resolve to ::1 first and reach
# another program listening on the same port.
printf 'Waiting for http://127.0.0.1:%s/healthz ' "$port"
for _ in $(seq 1 150); do
  if curl -fsS "http://127.0.0.1:$port/healthz" >/dev/null 2>&1; then
    echo " ok"
    echo
    echo "  Dashboard : http://127.0.0.1:$port/"
    echo "  Owner token (paste it into the sign-in field): $(cat .secrets/owner.token)"
    echo "  Verify    : ../verify/verify.sh http://127.0.0.1:$port \"\$(cat .secrets/owner.token)\" \"\$(cat .secrets/agent.token)\""
    exit 0
  fi
  printf '.'
  sleep 2
done
echo
echo "gateway did not answer; see: docker compose logs gateway dashboard-build" >&2
exit 1
